"""Builds app/src/main/assets/music.js from the song demos (demos/*.html are the single source).
Each demo's script is wrapped into a module that plays on the game's AudioContext:
  MUSIC.mods.<id>.start(version)  /  .stop()
The game's Settings menu lists every version (see SONG_LIST at the end of music.js)."""
import os, re
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
DEMOS = [('village', 'village_piano.html'), ('quiet', 'quiet_field.html'), ('porch', 'porch_light.html')]

def module(mid, fname):
    src = open(os.path.join(ROOT, 'demos', fname)).read()
    js = re.search(r'<script>(.*?)</script>', src, re.S).group(1)
    # use the game's audio context, output and reverb instead of creating new ones
    js = re.sub(r'function init\(\)\{if\(AC\)return;AC=new .*?rg\.connect\(out\);\}',
                'function init(){if(AC)return;const E=MUSIC.engine();AC=E.AC;out=E.out;rev=E.rev;}', js, flags=re.S)
    assert 'MUSIC.engine()' in js, mid
    # drop the demo page UI (stopAll/play and the click handlers) and add a small player
    js = js[:js.index('function stopAll(){')]
    js += '''
let _timer=null,_ver=null;
function stop(){for(const n of live){try{n.stop();}catch(e){}}live.length=0;clearInterval(_timer);_timer=null;_ver=null;if(typeof loopN!=='undefined')loopN=0;}
function start(v){init();if(!AC)return;stop();_ver=v;t0=AC.currentTime+.15;scheduleLoop(v,t0);nextLoop=t0+loopLen;
  _timer=setInterval(()=>{if(AC.currentTime>nextLoop-2){scheduleLoop(v,nextLoop);nextLoop+=loopLen;}if(live.length>4000)live.splice(0,2000);},250);}
return{start,stop,get ver(){return _ver;}};'''
    return f'MUSIC.mods.{mid}=(function(){{\n{js}\n}})();\n'

head = '''/* Cottage Meadow music (generated by tools/build_game_music.py from demos/*.html; do not edit by hand).
   Piano / harp / pad songs that play on the game's AudioContext. The chiptune songs stay in index.html (SONGS). */
const MUSIC={mods:{},_E:null,
  engine(){if(this._E)return this._E;if(typeof audioInit==='function')audioInit();const ac=AC;if(!ac)return{};
    const out=ac.createGain();out.gain.value=.55;out.connect(master);
    const len=ac.sampleRate*2.2,ir=ac.createBuffer(2,len,ac.sampleRate);
    for(let ch=0;ch<2;ch++){const a=ir.getChannelData(ch);for(let i=0;i<len;i++)a[i]=(Math.random()*2-1)*Math.pow(1-i/len,3.2);}
    const rev=ac.createConvolver();rev.buffer=ir;const rg=ac.createGain();rg.gain.value=.32;rev.connect(rg);rg.connect(out);
    return this._E={AC:ac,out,rev};}};
'''
tail = '''
/* every song the player can pick in Settings. kind 'chip' = index.html SONGS, 'mod' = a module above */
const SONG_LIST=[
  {id:'auto',name:'Auto (each place has its own song)'},
  {id:'chip:day',name:'Willow Village (8-bit)',kind:'chip',song:'day'},
  {id:'chip:forest',name:'Whisperwood (8-bit)',kind:'chip',song:'forest'},
  {id:'chip:lake',name:'Mirror Lake (8-bit)',kind:'chip',song:'lake'},
  {id:'chip:home',name:'Home (8-bit)',kind:'chip',song:'home'},
  {id:'village:piano',name:'Willow Village: solo piano',kind:'mod',mod:'village',ver:'piano'},
  {id:'village:pad',name:'Willow Village: piano + strings',kind:'mod',mod:'village',ver:'pad'},
  {id:'quiet:piano',name:'Quiet Field: solo piano',kind:'mod',mod:'quiet',ver:'piano'},
  {id:'quiet:pad',name:'Quiet Field: piano + soft pad',kind:'mod',mod:'quiet',ver:'pad'},
  {id:'quiet:harplow',name:'Quiet Field: piano + low harp',kind:'mod',mod:'quiet',ver:'harplow'},
  {id:'quiet:harpmid',name:'Quiet Field: piano + mid harp',kind:'mod',mod:'quiet',ver:'harpmid'},
  {id:'porch:piano',name:'Porch Light: solo piano',kind:'mod',mod:'porch',ver:'piano'},
  {id:'porch:porch',name:'Porch Light: porch version',kind:'mod',mod:'porch',ver:'porch'},
  {id:'porch:harp',name:'Porch Light: piano + harp',kind:'mod',mod:'porch',ver:'harp'},
];
'''
out = head + ''.join(module(m, f) for m, f in DEMOS) + tail
open(os.path.join(ROOT, 'app', 'src', 'main', 'assets', 'music.js'), 'w').write(out)
print('music.js', len(out))
