"""Export the market sprites for the game (Cottage Meadow v1.2).
Output: app/src/main/assets/market.png (atlas) + app/src/main/assets/market_atlas.js (rects).
Uses the same art as the mockup (tools/market_mock.py, jao.py, bins.py, turon.py)."""
import os, sys, json
from PIL import Image, ImageDraw, ImageFont
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from farmer import C
from jao import jao
from bins import seller as bins
from turon import turon
import market_mock as mm

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'app', 'src', 'main', 'assets')
parts = {}

def crop_alpha(im):
    bb = im.getbbox(); return im.crop(bb), bb

# fish stall (awning + back + counter + ice tray + chalkboard + scale), transparent background
im = Image.new('RGBA', (120, 120), (0, 0, 0, 0)); d = ImageDraw.Draw(im)
cy = mm.stall(im, 12, 26, 86, C('#3f6fb5'), C('#f2efe6'), 'SELL FISH', C('#2f568f'))
mm.counter(im, 10, cy + 20, 90)
d.rectangle([16, cy + 15, 94, cy + 20], fill=C('#dff2fb')); d.line([(16, cy + 15), (94, cy + 15)], fill=C('#ffffff'))
cols = [(C('#8fa3b8'), C('#dfe8ee')), (C('#c9a06a'), C('#f2e2c0')), (C('#5a7a5a'), C('#c8d8b8')), (C('#b0b8c4'), C('#ffffff'))]
for i in range(10):
    b, be = cols[i % 4]; mm.tiny_fish(d, 19 + i * 7, cy + 16 + (i % 2), b, be, flip=i % 3 == 0)
d.rectangle([22, cy - 2, 40, cy + 9], fill=C('#2e3a2e'), outline=C('#6e4626'))
for k in range(3): d.line([(25, cy + 1 + k * 3), (36 - k * 2, cy + 1 + k * 3)], fill=C('#dfe8ee'))
d.rectangle([76, cy + 5, 88, cy + 14], fill=C('#c4cad2'), outline=C('#5d636c')); d.ellipse([78, cy + 1, 86, cy + 6], fill=C('#dfe4ea'), outline=C('#5d636c'))
parts['fishStall'] = crop_alpha(im)

# animal stall: back part (awning, posts, wall) and the front counter separately (Bins stands between them)
im = Image.new('RGBA', (120, 120), (0, 0, 0, 0))
cy2 = mm.stall(im, 12, 26, 90, C('#4f8a3c'), C('#f2efe6'), 'ANIMALS', C('#3d6e2f'))
parts['animalBack'] = crop_alpha(im)
im2 = Image.new('RGBA', (120, 120), (0, 0, 0, 0)); d = ImageDraw.Draw(im2)
mm.counter(im2, 16, cy2 + 14, 84)
d.rectangle([24, cy2 + 6, 40, cy2 + 14], fill=C('#f2efe6'), outline=C('#6e4626'))
d.text((32, cy2 + 10), 'BUY', font=ImageFont.load_default(size=6), fill=C('#3d6e2f'), anchor='mm')
d.rectangle([80, cy2 + 4, 90, cy2 + 14], fill=C('#d8c48a'), outline=C('#8a6a35')); d.line([(82, cy2 + 6), (88, cy2 + 6)], fill=C('#8a6a35'))
parts['animalFront'] = crop_alpha(im2)
# Bins' spot relative to the stall (mock: stall x0=128 -> bins at 158, cy2-13)
binsOff = (158 - 128 + 12 - parts['animalBack'][1][0], cy2 - 13 - parts['animalBack'][1][1])
frontOff = (parts['animalFront'][1][0] - parts['animalBack'][1][0], parts['animalFront'][1][1] - parts['animalBack'][1][1])

# chick pen (empty fence; chicks are drawn by the game)
pen = Image.new('RGBA', (42, 19), (0, 0, 0, 0)); d = ImageDraw.Draw(pen)
d.rectangle([0, 3, 40, 17], fill=C('#cdb68a'))
for k in range(0, 41, 5): d.line([(k, 0), (k, 18)], fill=C('#8a5a30'))
d.line([(0, 3), (40, 3)], fill=C('#9a6438')); d.line([(0, 11), (40, 11)], fill=C('#9a6438'))
parts['pen'] = (pen, (0, 0, 42, 19))

# character frames
for name, fn, poses in (('jao', jao, ['idle', 'breath', 'raise', 'inhale', 'exhale']),
                        ('bins', bins, ['idle', 'breath', 'blink', 'push', 'push2']),
                        ('turon', turon, ['idle', 'breath', 'blink', 'wag'])):
    for p in poses:
        f = fn(p); parts[f'{name}_{p}'] = (f, (0, 0) + f.size)

# pack in rows
x = y = rowh = 0; W = 400; placed = {}
for k, (img, bb) in parts.items():
    w, h = img.size
    if x + w > W: x = 0; y += rowh + 1; rowh = 0
    placed[k] = (x, y, w, h, img); x += w + 1; rowh = max(rowh, h)
atlas = Image.new('RGBA', (W, y + rowh + 1), (0, 0, 0, 0))
for k, (px, py, w, h, img) in placed.items(): atlas.alpha_composite(img, (px, py))
atlas.save(os.path.join(OUT, 'market.png'))
meta = {k: [v[0], v[1], v[2], v[3]] for k, v in placed.items()}
meta['_binsOff'] = list(binsOff); meta['_frontOff'] = list(frontOff)
open(os.path.join(OUT, 'market_atlas.js'), 'w').write('/* generated by tools/export_market_sprites.py */\nwindow.MARKET_ATLAS=' + json.dumps(meta) + ';\n')
print(atlas.size, json.dumps(meta))
